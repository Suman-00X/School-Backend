/* Writes docs/ENDPOINTS.md from the live route table (the same source as /api/v1/openapi.json),
   so the endpoint list can never drift from the code. CI fails when it is out of date.

     npm run docs:endpoints */
import fs from "node:fs";
import path from "node:path";

/* The route table needs config to load, but nothing connects */
process.env.DATABASE_URL ||= "postgres://docs@localhost/docs";
process.env.MONGO_URI ||= "mongodb://localhost/docs";
process.env.JWT_SECRET ||= "docs";
process.env.LOG_LEVEL = "silent";

const { buildOpenApi } = await import("../src/common/openapi/openapi.js");
const { ALL_ROLES } = await import("../src/common/auth/roles.js");
const { default: v1 } = await import("../src/routes.js");

const spec = buildOpenApi(v1, {
  basePath: "/api/v1",
  title: "School Management API",
  version: "1.0.0",
  publicPaths: ["/api/v1/public"]
});

const rolesOf = operation => {
  const match = /Roles: ([^.]+)\./.exec(operation.description ?? "");
  if (!match) return operation.security?.length === 0 ? "Public (no token)" : "Any signed-in user";
  const roles = match[1].split(", ");
  return roles.length === ALL_ROLES.length ? "Everyone" : roles.join(", ");
};

const byModule = new Map();
for (const [route, methods] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    const module = route.split("/")[3];
    if (!byModule.has(module)) byModule.set(module, []);
    byModule.get(module).push({ method: method.toUpperCase(), route: route.replace(/\{(\w+)\}/g, ":$1"), operation });
  }
}

const ORDER = { GET: 0, POST: 1, PUT: 2, PATCH: 3, DELETE: 4 };
const total = [...byModule.values()].reduce((n, rows) => n + rows.length, 0);
const lines = [
  "# Endpoints (v1)",
  "",
  "<!-- Generated by `npm run docs:endpoints` from the route table. Do not edit by hand. -->",
  "",
  `${total} endpoints. Request and response schemas: \`GET /api/v1/openapi.json\`, or browse them at \`/api/docs\`. Conventions: [API.md](API.md).`,
  "",
  ...[...byModule.keys()].map(module => `- [${module}](#${module})`),
  ""
];
for (const [module, rows] of byModule) {
  lines.push(`## ${module}`, "", "| Method | Path | Action | Roles |", "|---|---|---|---|");
  rows.sort((a, b) => a.route.localeCompare(b.route) || ORDER[a.method] - ORDER[b.method]);
  for (const { method, route, operation } of rows) {
    const action = operation.summary.startsWith(method) ? "" : operation.summary;
    lines.push(`| ${method} | \`${route}\` | ${action} | ${rolesOf(operation)} |`);
  }
  lines.push("");
}

const target = path.resolve(import.meta.dirname, "../docs/ENDPOINTS.md");
fs.writeFileSync(target, lines.join("\n"));
console.log(`Wrote ${total} endpoints to docs/ENDPOINTS.md`);
process.exit(0);
